"""Generate the Statement of Applicability (HQ-IN-05).

Work register, section AJ3: for each of the 93 controls of ISO/IEC 27001:2022 Annex A, "applicability decided, how
it is met described, evidence kept". A bank's own security review asks for this document by name, and asks for it
early, so it is written now rather than after the meeting.

It is written to be true on 6 October 2026, which means most entries say the control is applicable and NOT yet in
place. That is what a Statement of Applicability is for. A document claiming 93 controls in place at a company that
is not yet incorporated, has no staff and has never held a board meeting would be worse than no document at all:
the first question a reviewer asks is for the evidence, and there would be none.

Status is one of:
  IN PLACE        built, and the evidence can be produced today
  PARTLY          some of it is built and the gap is named
  NOT YET         applicable, nothing built, owner and trigger named
  NOT APPLICABLE  with the reason, which is what a reviewer actually checks
"""
