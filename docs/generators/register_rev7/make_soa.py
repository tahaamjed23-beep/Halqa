def main():
    assert len(C) == 93, 'expected 93 Annex A controls, have %d' % len(C)
    os.makedirs(OUT, exist_ok=True)
    counts = {}
    for _, _, status, _, _ in C:
        counts[status] = counts.get(status, 0) + 1

    md = ['# Halqa Statement of Applicability', '',
          'Reference HQ-IN-05. ISO/IEC 27001:2022 Annex A, all 93 controls.', '',
          'For each control: whether it applies to Halqa, how it is met or why it does not apply, and where the '
          'evidence is. Written to be true on 6 October 2026, which is why most entries record a control as '
          'applicable and not yet in place.', '',
          'A document claiming 93 controls in place at a company that is not yet incorporated, has no staff and has '
          'never held a board meeting would be worse than no document: the first thing a reviewer asks for is the '
          'evidence, and there would be none. The gaps are named instead, with what closes each one.', '',
          '## Summary', '',
          '| Status | Controls | Meaning |', '| :-- | --: | :-- |',
          '| In place | %d | Built, and the evidence can be produced today |' % counts.get('IN PLACE', 0),
          '| Partly | %d | Some of it is built and the gap is named |' % counts.get('PARTLY', 0),
          '| Not yet | %d | Applicable, nothing built |' % counts.get('NOT YET', 0),
          '| Not applicable | %d | With the reason |' % counts.get('NOT APPLICABLE', 0),
          '', 'The three that matter most among those not yet in place are 8.16 monitoring, 5.24 incident '
          'response planning and 8.13 the untested backup restore. Each should close before the first member '
          'joins rather than before the first audit.', '']

    LABEL = {'IN PLACE': 'In place', 'PARTLY': 'Partly', 'NOT YET': 'Not yet', 'NOT APPLICABLE': 'Not applicable'}
    section = None
    TITLES = {'5': 'Organisational Controls', '6': 'People Controls', '7': 'Physical Controls',
              '8': 'Technological Controls'}
    for num, name, status, how, evidence in C:
        group = num.split('.')[0]
        if group != section:
            section = group
            md += ['## %s. %s' % (group, TITLES[group]), '']
        md += ['### %s %s' % (num, name), '',
               'Status: %s.' % LABEL[status], '',
               how, '',
               'Evidence: %s' % evidence, '']

    path = os.path.join(OUT, 'STATEMENT-OF-APPLICABILITY.md')
    io.open(path, 'w', encoding='utf-8').write('\n'.join(md))
    print('controls %d | in place %d, partly %d, not yet %d, not applicable %d'
          % (len(C), counts.get('IN PLACE', 0), counts.get('PARTLY', 0),
             counts.get('NOT YET', 0), counts.get('NOT APPLICABLE', 0)))
    print('written', path)


if __name__ == '__main__':
    main()
